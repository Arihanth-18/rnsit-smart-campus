-- RNSIT Smart Campus schema (PostgreSQL / Neon). Safe to re-run.

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name          TEXT        NOT NULL,
  email         TEXT        NOT NULL UNIQUE,          -- stored lower-case
  password_hash TEXT        NOT NULL,
  role          TEXT        NOT NULL CHECK (role IN ('student', 'admin')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS issues (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1049) PRIMARY KEY,
  reporter_id INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  description TEXT        NOT NULL,
  category    TEXT        NOT NULL,
  priority    TEXT        NOT NULL CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
  score       NUMERIC(3,2) NOT NULL,
  location    TEXT        NOT NULL DEFAULT 'Not specified',
  assigned_to TEXT        NOT NULL,
  status      TEXT        NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'In Progress', 'Resolved')),
  severity    SMALLINT    NOT NULL CHECK (severity BETWEEN 1 AND 5),
  impact      SMALLINT    NOT NULL CHECK (impact   BETWEEN 1 AND 5),
  urgency     SMALLINT    NOT NULL CHECK (urgency  BETWEEN 1 AND 5),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS issues_reporter_idx ON issues (reporter_id, created_at DESC);
CREATE INDEX IF NOT EXISTS issues_status_idx   ON issues (status);
CREATE INDEX IF NOT EXISTS issues_priority_idx ON issues (priority);
CREATE INDEX IF NOT EXISTS issues_created_idx  ON issues (created_at DESC);

-- Audit trail of status changes made by admins
CREATE TABLE IF NOT EXISTS issue_events (
  id          INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  issue_id    INTEGER     NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
  actor_id    INTEGER     REFERENCES users(id) ON DELETE SET NULL,
  from_status TEXT,
  to_status   TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS issue_events_issue_idx ON issue_events (issue_id, created_at);

-- Replies written by admins; shown to students on complaint tracking
CREATE TABLE IF NOT EXISTS issue_responses (
  id         INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  issue_id   INTEGER     NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
  admin_id   INTEGER     REFERENCES users(id) ON DELETE SET NULL,
  message    TEXT        NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS issue_responses_issue_idx ON issue_responses (issue_id, created_at);
